#!/bin/bash

# Default location, or the first argument if the user gives one
DEST="${1:-$HOME/radius-projects/website-project}"

# Protect existing directories
if [ -e "$DEST" ]; then
    echo "Error: $DEST already exists. Nothing was changed."
    exit 1
fi

# Create the directory structure
mkdir -p "$DEST/css" "$DEST/js" "$DEST/images"

# index.html
cat > "$DEST/index.html" << 'EOF'
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>My Website</title>
    <link rel="stylesheet" href="css/style.css">
</head>
<body>
    <h1>Welcome to My Website</h1>
    <p>This project was generated by a Bash script.</p>
    <script src="js/script.js"></script>
</body>
</html>
EOF

# css/style.css
cat > "$DEST/css/style.css" << 'EOF'
body {
    font-family: Arial, sans-serif;
    margin: 40px;
    background-color: #f4f4f4;
    color: #333;
}

h1 {
    color: #0077cc;
}
EOF

# js/script.js
cat > "$DEST/js/script.js" << 'EOF'
console.log("Website loaded successfully!");
EOF

# README files
cat > "$DEST/README.md" << 'EOF'
# Website Project

A basic website project with HTML, CSS and JavaScript, generated by a Bash script.
EOF

cat > "$DEST/css/README.md" << 'EOF'
# CSS Directory

This folder holds the stylesheets that control how the website looks.
EOF

cat > "$DEST/js/README.md" << 'EOF'
# JavaScript Directory

This folder holds the JavaScript files that add behaviour to the website.
EOF

cat > "$DEST/images/README.md" << 'EOF'
# Images Directory

This folder holds image files for the website, such as .png, .jpg and .svg.
EOF

# Completion message
echo "Website project created at: $DEST"
